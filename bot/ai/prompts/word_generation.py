from bot.ai.provider import GenerateWordsRequest
from bot.database.models.enums import PartOfSpeech


def build_generate_words_prompt(request: GenerateWordsRequest) -> str:
    known = "\n".join(f"- {w}" for w in request.known_words[:60]) or "(ще немає вивчених слів)"
    exclude = ", ".join(sorted(request.exclude_lemmas)) or "(немає)"
    topics = ", ".join(request.topics_hint) or "будь-які практичні, повсякденні теми"
    mistakes = ", ".join(request.mistake_topics) or "(немає даних)"

    return f"""Ти -- експерт із викладання англійської мови за системою CEFR.

Згенеруй рівно {request.count} нових англійських слів або сталих виразів
для учня рівня {request.level.value}.

Слова/вирази, які учень вже знає або вивчає (НЕ повторюй їх і НЕ пропонуй
прямі спряження/форми множини тих самих лем):
{known}

Явно уникай цих лем (крапка в крапку): {exclude}

Обирай нову лексику, яка логічно ДОПОВНЮЄ вже наявний словниковий запас --
синоніми, антоніми, спільна тема, стійкі колокації, фразові дієслова, ідіоми.
Теми, які варто врахувати: {topics}
Теми, у яких учень нещодавно припускався помилок (можна закріпити суміжною
лексикою): {mistakes}

Рівень складності кожного слова має бути не вищим, ніж на один крок CEFR
вище за {request.level.value} (тобто прийнятні рівні: {request.level.value}
і, за потреби, один рівень вище).

Для кожного слова вкажи: лему (англійською, у словниковій формі),
переклад українською, приклад речення англійською з цим словом, переклад
цього прикладу українською, CEFR-рівень, частину мови, тему, фонетичну
транскрипцію у форматі IPA окремо для британської (transcription_uk) та
американської (transcription_us) вимови -- IPA-символи в похилих рисках,
наприклад "/əˈfɔːdəbl/" -- та (якщо доречно) синоніми, антоніми, колокації.
Транскрипція має точно відповідати вимові саме цього слова; якщо British і
American вимова практично однакові, вкажи однакове значення в обох полях.
Обирай практично цінну, вживану лексику, а не рідкісні або книжні слова."""


def build_transcription_prompt(lemma: str, part_of_speech: PartOfSpeech) -> str:
    return f"""Дай IPA-транскрипцію для англійського слова/виразу "{lemma}"
({part_of_speech.value}).

Вкажи окремо британську (transcription_uk) та американську (transcription_us)
вимову, у форматі "/.../ " (IPA-символи в похилих рисках, наприклад
"/əˈfɔːdəbl/"). Якщо вимова практично однакова, встав однакове значення в
обидва поля."""
