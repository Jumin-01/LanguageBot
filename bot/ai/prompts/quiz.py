from bot.database.models.enums import CEFRLevel


def build_generate_quiz_sentence_prompt(
    lemma: str, translation: str, level: CEFRLevel, known_words: list[str]
) -> str:
    known = ", ".join(known_words[:30]) or "(небагато)"
    return f"""Учень рівня {level.value} вивчає слово/вираз "{lemma}"
(переклад: "{translation}").

Він уже знає ці слова: {known}.

Склади ОДНЕ нове, природне речення англійською мовою рівня {level.value},
яке використовує "{lemma}" у типовому контексті, і подай точний переклад
цього речення українською. Речення має бути коротким (до 12 слів), НАСКІЛЬКИ
МОЖЛИВО використовувати вже відомі учню слова замість незнайомої лексики
(окрім самого "{lemma}"), і не збігатися дослівно зі словниковим прикладом
цього слова."""


def build_evaluate_translation_prompt(
    sentence_en: str, reference_uk: str, user_answer_uk: str
) -> str:
    return f"""Оціни переклад учня.

Англійське речення: "{sentence_en}"
Еталонний переклад українською: "{reference_uk}"
Переклад учня: "{user_answer_uk}"

Переклад учня не повинен збігатися з еталоном дослівно -- зараховуй як
правильний будь-який переклад, що коректно передає зміст речення, навіть
якщо формулювання, порядок слів чи синоніми відрізняються. Незначні
орфографічні помилки, які не змінюють зміст, ігноруй. Визнач переклад
неправильним лише якщо він спотворює зміст або пропускає ключову інформацію."""
