from bot.database.models.enums import CEFRLevel


def build_rank_next_word_prompt(
    user_level: CEFRLevel, known_words_sample: list[str], candidate_lemmas: list[str]
) -> str:
    known = ", ".join(known_words_sample[:20]) or "(ще немає)"
    candidates = "\n".join(f"- {lemma}" for lemma in candidate_lemmas)

    return f"""Ти аналізуєш словниковий запас учня рівня {user_level.value} і
допомагаєш обрати, яке слово вивчати наступним.

Учень уже знає (вибірка): {known}

Нижче -- кандидати на вивчення наступного. Це вже відфільтрований список
(усі кандидати підходять за рівнем і ще не вивчені) -- НЕ пропонуй інші
слова, НЕ пропускай жодного з цього списку, оціни РІВНО ці:
{candidates}

Для кожного кандидата постав оцінку (score) від 0.0 до 1.0: наскільки
логічно він доповнює вже відомий словниковий запас учня (зв'язок через
синоніми/антоніми/колокації/спільну тему, практична цінність, можливість
одразу скласти з ним корисні речення чи фрази з уже відомих слів). Дай
коротке обґрунтування (reason) для кожної оцінки."""
